//! x86 の I/O ポートアクセス。
//!
//! `in` / `out` 命令をここに集約する。同じインラインアセンブリを各所へ複製すると、
//! `options(...)` の指定漏れのような間違いが個別に紛れ込む。
//!
//! # 呼び出し側に要求すること
//!
//! [`outb`] と [`inb`] は任意のポートを読み書きできるプリミティブで、
//! どのポートに何を書いてよいかの判断は呼び出し側にある。
//!
//! - 書き込みそのものが装置の状態遷移を起こす。値を戻せば元に戻る、
//!   という前提が成り立たない。
//! - 読み出しにも副作用がありうる。装置によっては読み出しが割り込み状態や
//!   バッファをクリアするので、「読むだけだから安全」とは言えない。
//! - 同じ装置へ複数の実行文脈から触らないこと。8259A のように複数回の
//!   書き込みで1つの手順を成す装置は、途中に別の書き込みが混ざると
//!   中途半端な状態で固まる。
//!
//! したがって直接呼ぶのは装置ごとのドライバ（[`crate::serial`]、`kernel::irq::pic`）
//! だけにとどめ、その中で契約を満たしたうえで安全な API として公開する。

/// 1 バイトをポート `port` へ書き込む。
///
/// # Safety
///
/// `port` が意図した意味を持つ有効な I/O ポートであること、および同一ポートへの
/// 並行アクセスが競合しないこと。モジュールの doc の3点も満たすこと。
#[inline]
pub unsafe fn outb(port: u16, value: u8) {
    // SAFETY: `out dx, al` は指定ポートへ1バイト出力するだけで、メモリには
    // 触れない。ポート番号の妥当性と排他性は呼び出し元の契約である。
    unsafe {
        core::arch::asm!(
            "out dx, al",
            in("dx") port,
            in("al") value,
            options(nomem, nostack, preserves_flags),
        );
    }
}

/// 直前の I/O 書き込みが古いデバイスへ届くまでの時間を稼ぐ。
///
/// 8259 PIC のような ISA 世代のデバイスは、連続した `out` に追いつけないことがある。
/// POST 用の診断ポート 0x80 へ1バイト捨て書きし、そのバス転送の分だけ待つ
/// （Linux の `outb_p` と同じ発想）。
///
/// QEMU では不要だが、実機を見据えて ICW の各段の後に挟む。
#[inline]
pub fn io_wait() {
    // SAFETY: 0x80 は POST コード用の診断ポートで、どのデバイスもここを制御
    // レジスタとして使わない。書き込みに副作用が無く、値も参照されない。
    unsafe {
        outb(0x80, 0);
    }
}

/// ポート `port` から1バイト読み込む。
///
/// # Safety
///
/// [`outb`] と同じ。`port` の妥当性と排他性は呼び出し側の責任である。
#[inline]
pub unsafe fn inb(port: u16) -> u8 {
    let value: u8;
    // SAFETY: `in al, dx` は指定ポートから1バイト読み込むだけで、メモリには
    // 触れない。ポート番号の妥当性と排他性は呼び出し元の契約である。
    unsafe {
        core::arch::asm!(
            "in al, dx",
            out("al") value,
            in("dx") port,
            options(nomem, nostack, preserves_flags),
        );
    }
    value
}
