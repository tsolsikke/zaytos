//! x86 の I/O ポートアクセス。
//!
//! `in` / `out` 命令をここに集約する。M1 の時点では [`crate::serial`] の
//! private な関数だったが、M4-c-3 で PIC も同じ命令を必要としたため共有
//! モジュールへ切り出した。同じ 3 行のインラインアセンブリを各所へ複製
//! すると、`options(...)` の指定漏れのような間違いが個別に紛れ込む。
//!
//! この 2 つの関数だけが `unsafe` で、呼び出し側はそれぞれの契約
//! （ポート番号の妥当性と排他性）を満たしたうえで安全な API を組み立てる。
//!
//! ## 呼び出し側に要求すること
//!
//! これは**任意のポートを読み書きできるプリミティブ**であり、どのポートに
//! 何を書いてよいかの判断は完全に呼び出し側にある。Rust の型では表現でき
//! ない領域なので、`unsafe fn` のまま置き、契約を文章で示す。
//!
//! - **書き込むポートの意味と副作用を理解していること。** I/O ポートは
//!   メモリと違い、書き込みそのものが装置の状態遷移を起こす。値を戻せば
//!   元に戻る、という前提が成り立たない。
//! - **読み出しにも副作用がありうること。** 装置によっては読み出しが
//!   割り込み状態やバッファをクリアする。「読むだけだから安全」とは
//!   言えない。
//! - **同じ装置へ複数の実行文脈から触らないこと。** 8259A のように、
//!   複数回の書き込みで 1 つの手順を成す装置は、途中に割り込みが入って
//!   別の書き込みが混ざると中途半端な状態で固まる。
//!
//! したがって、これらを直接呼ぶのは装置ごとのドライバ
//! （[`crate::serial`], `kernel::pic`）だけにとどめ、その中で契約を満たした
//! うえで安全な API として公開する。

/// 1 バイトをポート `port` へ書き込む。
///
/// # Safety
/// 呼び出し側は `port` が意図した意味を持つ有効な I/O ポートであること、
/// および同一ポートへの並行アクセスが競合しないことを保証しなければならない。
#[inline]
pub unsafe fn outb(port: u16, value: u8) {
    // SAFETY: `out dx, al` は指定ポートへ1バイト出力するだけで、メモリには
    // 触れない。呼び出し元がポート番号の妥当性・排他性を保証する契約。
    unsafe {
        core::arch::asm!(
            "out dx, al",
            in("dx") port,
            in("al") value,
            options(nomem, nostack, preserves_flags),
        );
    }
}

/// ポート `port` から1バイト読み込む。
///
/// # Safety
/// [`outb`] と同様、`port` の妥当性・排他性は呼び出し側の責任。
#[inline]
pub unsafe fn inb(port: u16) -> u8 {
    let value: u8;
    // SAFETY: `in al, dx` は指定ポートから1バイト読み込むだけで、メモリには
    // 触れない。呼び出し元がポート番号の妥当性・排他性を保証する契約。
    unsafe {
        core::arch::asm!(
            "in al, dx",
            out("al") value,
            in("dx") port,
            options(nomem, nostack, preserves_flags),
        );
    }
    value
}
