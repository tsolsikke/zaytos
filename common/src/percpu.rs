//! per-CPU アクセサの seam（ADR-0023 §3）。
//!
//! SMPをBKL（ビッグカーネルロック）ファーストで入れる（ADR-0023）にあたり、
//! 「どのコアのデータか」をコード上で表現する継ぎ目を、振る舞いを変えずに
//! 先に用意する。当面はシングルコア（ADR-0002）なので [`cpu_id`] は常に `0` を
//! 返し、per-CPUデータは要素数 1 の配列で保持する。BKL本体（higher-half B完了後）で
//! 実データをここへ寄せ、`cpu_id()` をAPIC ID / GSベース由来へ差し替える。
//!
//! # なぜ器だけを先に作るか
//!
//! per-CPUデータへのアクセスを最初から [`PerCpu::this_cpu`] / [`cpu_id`] 経由に
//! 統一しておけば、実データを寄せる各段（nesting・GDT/TSS・スケジューラの現在タスク）で
//! 直接 static を触る箇所が残らず、後でGSベース読みへ差し替えるときに触る面が
//! アクセサ 1 箇所で済む。
//!
//! # GSベースはこの seam では触らない。GS化が何を与え何を与えないか
//!
//! seam では [`cpu_id`] は定数 `0`、[`PerCpu`] は配列索引のままにし、GSの初期化は
//! 温存する（ADR-0024「SMP非閉塞」でGSベースを未使用のまま残している）。
//!
//! BKL本体でGS化しても、この器の構造（`[T; MAX_CPUS]` を [`cpu_id`] で引く）は
//! そのままである。GS化で変わるのは [`cpu_id`] がGS（またはAPIC ID）読みになる点
//! だけで、[`PerCpu::this_cpu`] は依然として配列を索引する。得られるのは
//! [`cpu_id`] の高速化であって、データ自体がGS相対オフセットへ移るわけではない。
//! したがってfalse sharing（[`MAX_CPUS`] の注意）はGS化しても残り、アクセスは
//! 2段（`cpu_id()` → 索引）のままである。BKLではカーネル内へ同時に入れるのは
//! 1コアだけで、per-CPUデータの同時アクセスは限られるため、これで十分である。
//!
//! データ自体をGS相対オフセットへ置く「集約ブロック形式」（コアごとに1つの
//! per-CPUブロックをGSベースへ置き、`gs:[offset]` で直に読む）にするなら、
//! [`PerCpu`] から集約ブロックへの移行が別途必要になる（false sharingの解消も
//! そこで行う）。これはフル細粒度SMP（`vision.md`）へ進むときに検討する。

/// サポートするCPU数の上限。
///
/// **S3-b-2a で `1` から `2` へ上げた。** AP はまだ起こさないので、実際に走るのは
/// bootstrap processor だけである。上げた理由は 2 つある。
///
/// - **`cpu_id()` が非 `0` を返しても配列外にならない状態を作るため。**
///   S3-a の tripwire（`task::require_bootstrap_processor`）の破壊確認は
///   `cpu_id()` に非 `0` を返させる形で行うが、`MAX_CPUS = 1` のままだと
///   `this_cpu_ptr` が配列外を指し、**破壊が別の未定義動作を作ってしまう。**
/// - **`2` は最小の必要値である。** tripwire の破壊に必要なのは「非 `0` が配列内で
///   あること」だけなので、`1` より大きい最小の値で足りる。**必要以上に上げない。**
///
/// # **上げた副作用: 覆いの報告の「覆えていない」側が、どの構成でも評価されなくなった**
///
/// `MAX_CPUS = 1` のときは `-smp 2` の項目が「2 コア列挙 / 1 スロット」で警告側を
/// 通していた。**`2` へ上げるとそれが「2 コア列挙 / 2 スロット」になり、覆えている
/// 側しか通らない。** `-smp 4` の項目は**存在しない**（`-smp` を渡す項目は
/// `acpi-smp-test` の 1 つで、コア数は `2` 固定である）。
///
/// **したがって警告側は現在どの構成でも評価されていない。** 覆いの報告そのものは
/// 毎回出るが、`false` の枝は通らない。**b-2b で `-smp 4` の構成を足すときに
/// 再び評価される**ので、そちらの到達条件に入れてある（`roadmap.md`）。
/// **記録しておくのは、「検査はあるが片側が通っていない」状態を見えなくしない
/// ためである。**
///
/// # **上げると検査が1つ効かなくなる。上げる前に読むこと**
///
/// `acpi-smp-test smp4-more-cpus-than-slots`（`-smp 4`）は**`MAX_CPUS < 4`である
/// ことに依存している。** 覆いの報告の「覆えていない」側を評価する唯一の構成が
/// これで、**`4` 以上へ上げるとこの検査の `false` 側が再び評価されなくなる**
/// （`-smp 8` の構成を足す必要が出る）。**`2` で止めている間はこの検査が生き続ける。**
///
/// **上げるときは、同時に上の構成を用意すること。** 気づかずに上げると、
/// 検査は緑のまま片側が通らなくなる。
///
/// # per-CPU スタックを静的に置くなら `2` が上限である
///
/// `StackBlock` は 108.0 KiB で、**静的配列で二重化すると 2MiB 境界までの余裕が
/// 260.0 KiB から 152.0 KiB へ減る。`MAX_CPUS = 4` では境界を越える**（PML4[511] の
/// PT 枚数が 3 から 4 へ増え、恒等除去のフレーム会計が動く）。ガードは各スタックの
/// 下にあるので**共有できず、増分は 1 コアあたり 108.0 KiB ちょうどで削れない。**
/// 詳細は `docs/roadmap.md` の S3-b-2b-2。
///
/// **b-2b で AP を起こすときは、実際のコア数の上限へ引き上げる必要がある。**
///
/// # `MAX_CPUS > 1` にするときの注意
///
/// per-CPUデータを `[T; MAX_CPUS]` で持つと、`MAX_CPUS > 1` では隣接要素が同一
/// キャッシュラインに載りうる。[`crate::critical`] の入れ子深さのようなホットな
/// カウンタでは、これがfalse sharingとして実測できる差になる。BKLでは競合が
/// 限られ性能は当面の目標でないので現在の素朴な配列で問題ないが、`MAX_CPUS > 1`
/// にする際は、各要素をキャッシュライン境界へアラインするか、データ自体を
/// コアごとの別領域へ置く集約ブロック形式（モジュールドキュメントのGS化の節を
/// 参照）へ移す必要がある。単に [`cpu_id`] をGS読みへ差し替えるだけでは、
/// 配列索引が残るためfalse sharingは解消しないことに注意する。
use core::sync::atomic::{AtomicUsize, Ordering};

pub const MAX_CPUS: usize = 2;

/// 現在実行中のCPUの番号（`0..MAX_CPUS`）を返す。
///
/// # 現状は常に `0`
///
/// シングルコア前提（ADR-0002）のため、当面は無条件に `0` を返す。BKL本体で
/// APIC ID / GSベースから実際の番号を読む形へ差し替える。
///
/// # `0` を返すことに依存したコードを書かないこと
///
/// 「どうせ `0` だから」という理由で境界チェックを省いたり、配列の先頭要素を
/// 直接触ったりしてはならない。そうしたコードは `MAX_CPUS > 1` にした瞬間に
/// 静かに壊れる。per-CPUデータへは必ず [`PerCpu::this_cpu`] 経由でアクセスし、
/// 索引はこの関数の戻り値を使う。
/// 自コアの CPU 番号を読む実装を差し替えるための器（S3-b-1）。
///
/// `0` は「未設定」を表す。**関数ポインタの値が `0` になることはない**ので、
/// 有効な実装と衝突しない。
static CPU_ID_READER: AtomicUsize = AtomicUsize::new(READER_NOT_INSTALLED);

/// [`CPU_ID_READER`] が未設定であることを表す値。
const READER_NOT_INSTALLED: usize = 0;

/// 自コアの CPU 番号を読む実装を据える（S3-b-1）。
///
/// # なぜ関数ポインタで差し替えるのか。**`common` に APIC の知識を置かないため**
///
/// 実 ID の出所は Local APIC の ID レジスタで、その仮想アドレスとビット位置は
/// `kernel` 側の知識である。`common` は bootloader からも使われるので、
/// レジスタのオフセットやシフト量をここへ写すと、**同じ事実が 2 箇所に出て
/// 片方が古くなる。** 器だけをここに置き、中身は `kernel` が据える。
///
/// 間接呼び出しの費用は、実装が行う MMIO 読みに比べて小さい。
///
/// # Safety
///
/// - `reader` は常に `0..`[`MAX_CPUS`] の値を返すこと。**範囲外を返すと
///   [`PerCpu::this_cpu_ptr`] が配列外を指す。**
/// - **割り込み文脈から呼ばれうる。** `reader` は再入可能で、ロックを取らず、
///   パニックしないこと（[`crate::critical`] の入れ子深さの読みから通る）。
/// - 起動時に 1 回だけ呼ぶこと。
pub unsafe fn install_cpu_id_reader(reader: fn() -> usize) {
    CPU_ID_READER.store(reader as usize, Ordering::Relaxed);
}

/// 自コアの CPU 番号を読む実装が据えられているか。
///
/// **据える前と後で戻り値が変わらないことを確かめる**ために公開している
/// （`MAX_CPUS = 1` ではどちらも `0` を返すので、値だけでは区別できない）。
pub fn cpu_id_reader_installed() -> bool {
    CPU_ID_READER.load(Ordering::Relaxed) != READER_NOT_INSTALLED
}

/// 現在実行中のCPUの番号（`0..MAX_CPUS`）を返す。
///
/// # 据える前は `0` を返す
///
/// GDT/TSS の構築（`gdt::init`）は Local APIC を写像するより前に
/// [`PerCpu::this_cpu_ptr`] を通るので、**実装が据わる前に呼ばれる。**
/// その時点で走っているのは bootstrap processor だけなので `0` が正しい。
///
/// # `MAX_CPUS = 1` の間は、据える前と後で値が変わらない
///
/// どちらも `0` を返すため、**値だけでは「実装が据わって MMIO 読みが成立して
/// いる」ことを確かめられない**（「同値である間は分類の誤りが観測できない」）。
/// 据えた側で、読み取りが成立していることを**`0` 以外の値**で示すこと
/// （`kernel` は Local APIC の Version レジスタを併読している）。
#[inline]
pub fn cpu_id() -> usize {
    // 破壊 (S3-b-2a, percpu-fake-nonzero-cpu-id): 非 `0` を返す。
    //
    // **`MAX_CPUS > 1` でなければこの破壊は作れない。** `MAX_CPUS = 1` のまま
    // 非 `0` を返すと [`PerCpu::this_cpu_ptr`] が配列外を指し、**破壊が別の
    // 未定義動作を作ってしまう。** S3-b-2a で `MAX_CPUS` を 2 へ上げたので、
    // `1` は配列内であり安全に作れる。
    //
    // **これが示すのは「分岐が働くこと」だけである。** `task` 側の tripwire
    // （`require_bootstrap_processor`）が非 `0` を見て停止する経路を通ることを
    // 確かめるだけで、**実際の並行アクセスは示さない。** 機序の直接観測は
    // AP がタスクを実行する段の到達条件である。
    #[cfg(feature = "percpu-fake-nonzero-cpu-id")]
    return 1;

    #[cfg(not(feature = "percpu-fake-nonzero-cpu-id"))]
    {
        cpu_id_inner()
    }
}

/// [`cpu_id`] の本体。破壊 feature が本体を差し替えるので分けてある。
// 破壊ビルドでは [`cpu_id`] が定数を返して本体へ到達しないので未使用になる。
#[cfg_attr(feature = "percpu-fake-nonzero-cpu-id", allow(dead_code))]
#[inline]
fn cpu_id_inner() -> usize {
    let raw = CPU_ID_READER.load(Ordering::Relaxed);
    if raw == READER_NOT_INSTALLED {
        return 0;
    }
    // SAFETY: `install_cpu_id_reader` は `fn() -> usize` の値だけを格納し、
    // 未設定を表す 0 は関数ポインタとして現れない。したがって raw は
    // 有効な関数ポインタである。呼び出し側契約により reader は再入可能で
    // 範囲内の値を返す。
    let reader: fn() -> usize = unsafe { core::mem::transmute::<usize, fn() -> usize>(raw) };
    reader()
}

/// CPUごとに 1 つずつ値を持つ器。
///
/// 実データは `[T; MAX_CPUS]` で保持し、[`this_cpu`][Self::this_cpu] が
/// [`cpu_id`] で現在のCPUの要素を引く。`AtomicUsize` のような内部可変な `T` を
/// 入れれば、`&T` 経由でそのまま更新できる（[`crate::critical`] の入れ子深さが
/// この形になる）。
///
/// `T: Sync` なら `PerCpu<T>` も自動で `Sync` になる（`[T; N]` の `Sync` を
/// そのまま継ぐ）ので、`static` として置ける。
///
/// # `#[repr(transparent)]` にする理由
///
/// GDT/TSS のように「`PerCpu<T>` のアドレスがそのまま先頭スロットのアドレス」で
/// あることに依存する箇所がある（`MAX_CPUS = 1` で `this_cpu_ptr(&X)` が `&X` と
/// 同じアドレスを返し、`sgdt`/`str` が読み戻す実体と一致する）。既定の
/// `#[repr(Rust)]` では単一フィールドでもフィールドオフセット 0 は言語仕様上の
/// 保証ではない（現実の rustc では 0 になるが、それに乗るのは「偶然成り立って
/// いる」に留まる）。非ZSTフィールドが `slots` 1 つだけなので
/// `#[repr(transparent)]` を付けられ、`PerCpu<T>` のレイアウトが `[T; MAX_CPUS]`
/// と同一であることが言語仕様上の保証になる（オフセット 0・同一アドレス）。
/// このプロジェクトの「偶然成り立つを構造で保証へ格上げする」方針に合わせる。
#[repr(transparent)]
pub struct PerCpu<T> {
    slots: [T; MAX_CPUS],
}

impl<T> PerCpu<T> {
    /// 各CPUの初期値を与えて器を作る。
    ///
    /// `const fn` なので `static` の初期化子として使える。
    pub const fn new(slots: [T; MAX_CPUS]) -> Self {
        Self { slots }
    }

    /// 現在のCPU（[`cpu_id`]）に対応する要素への参照を返す。
    ///
    /// 索引は必ず [`cpu_id`] 経由で、`0` 決め打ちにしない（[`cpu_id`] の注意を
    /// 参照）。BKL本体でGS化しても索引する構造自体は変わらず、[`cpu_id`] の
    /// 実装だけがGS（またはAPIC ID）読みへ差し替わる（モジュールドキュメントの
    /// GS化の節を参照）。
    #[inline]
    pub fn this_cpu(&self) -> &T {
        &self.slots[cpu_id()]
    }

    /// 現在のCPU（[`cpu_id`]）のスロットへの生ポインタ。
    ///
    /// [`this_cpu`][Self::this_cpu] が `&T`（読み取り・内部可変向け）を返すのに
    /// 対し、こちらは可変な書き込み（GDT/TSSの構築、RSP0の更新）向けに生ポインタ
    /// を返す。`static mut PerCpu<T>` を `addr_of_mut!` で取り、**参照（`&mut`）を
    /// 作らずに** スロットを書き換える既存の規律（GDT/TSS/SCHEDULER）へ合わせる。
    ///
    /// # なぜ `unsafe fn` にするか
    ///
    /// 実装は `addr_of_mut!((*this).slots)` というフィールド射影を行うため、
    /// `this` が有効な `PerCpu<T>` を指していることに依存する。安全な関数として
    /// 公開すると、無効なポインタを渡せてしまい未定義動作を安全側の顔で招く。
    /// base検査の SAFETY 規律（各 unsafe に内容のある契約を添える）に合わせ、
    /// `unsafe fn` にして「有効なポインタを渡す」責務を呼び出し側の契約へ移す。
    ///
    /// # 不変条件（この関数自身が保証すべきこと）
    ///
    /// 内部で `cpu_id()` 分だけポインタを進めるため、`cpu_id() < MAX_CPUS` が
    /// 成り立たないと配列外へのポインタ演算になり未定義動作である。`cpu_id()` は
    /// この関数の内部で呼ばれる（呼び出し側は渡さない）ので、これは SAFETY 契約
    /// ではなく**関数自身の不変条件**である。現在は `cpu_id()` が定数 `0`・
    /// `MAX_CPUS = 1` なので自明に成立する。BKL本体で `cpu_id()` が実CPU idを
    /// 返すようになったら、この不変条件を誰が保証するかを決める必要がある
    /// （`cpu_id()` 側で `0..MAX_CPUS` に収める / ここで `debug_assert!` する /
    /// 起動時にコア数 `> MAX_CPUS` なら halt する、のいずれか）。APを起こすときに
    /// 実際に踏む箇所である。
    ///
    /// # Safety
    ///
    /// - `this` は有効で整列済みの、生きている `PerCpu<T>` を指すポインタである
    ///   こと。典型的には `core::ptr::addr_of_mut!(STATIC)` から得る。null や
    ///   ダングリングなポインタを渡してはならない。
    /// - 返した生ポインタを通じた**書き込み**は、そのスロットへ他の実行文脈が同時に
    ///   アクセスしない区間（起動時の単一文脈、または `IF=0` のクリティカル区間）で
    ///   行うこと。[`PerCpu`] は配置を提供するだけで同期は提供しない。per-CPU でも
    ///   **同一コアの割り込みハンドラは同じスロットへ触れる**ので、「per-CPU なら
    ///   競合しない」ではない。
    /// - 返したポインタからの**アドレス計算のみ**（deref せず `as u64` 等）は、上の
    ///   区間要件を要しない。ポインタを deref して**スロットの中身を読む**場合は、
    ///   書き込みと同じ区間要件が要る（整列した `u64` の読みは実機では分割されない
    ///   が、契約としては書き込みと同格に扱う）。
    #[inline]
    pub unsafe fn this_cpu_ptr(this: *mut Self) -> *mut T {
        // SAFETY: 呼び出し側契約により `this` は有効な PerCpu<T> を指す。
        // addr_of_mut! で slots への参照を作らずに先頭要素へのポインタを取り、
        // cpu_id() 分ずらす。cpu_id() < MAX_CPUS（上の不変条件）なので配列内に収まる。
        unsafe {
            let base = core::ptr::addr_of_mut!((*this).slots) as *mut T;
            base.add(cpu_id())
        }
    }
}
