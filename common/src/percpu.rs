//! per-CPU アクセサの seam（ADR-0023 §3）。
//!
//! SMPをBKL（ビッグカーネルロック）ファーストで入れる（ADR-0023）にあたり、
//! 「どのコアのデータか」をコード上で表現する継ぎ目を、振る舞いを変えずに
//! 先に用意する。当面はシングルコア（ADR-0002）なので [`cpu_id`] は常に `0` を
//! 返し、per-CPUデータは要素数 1 の配列で保持する。BKL本体（higher-half B完了後）で
//! 実データをここへ寄せ、`cpu_id()` をAPIC ID / GSベース由来へ差し替える。
//!
//! # なぜ器だけを先に作るか
//!
//! per-CPUデータへのアクセスを最初から [`PerCpu::this_cpu`] / [`cpu_id`] 経由に
//! 統一しておけば、実データを寄せる各段（nesting・GDT/TSS・スケジューラの現在タスク）で
//! 直接 static を触る箇所が残らず、後でGSベース読みへ差し替えるときに触る面が
//! アクセサ 1 箇所で済む。
//!
//! # GSベースはこの seam では触らない。GS化が何を与え何を与えないか
//!
//! seam では [`cpu_id`] は定数 `0`、[`PerCpu`] は配列索引のままにし、GSの初期化は
//! 温存する（ADR-0024「SMP非閉塞」でGSベースを未使用のまま残している）。
//!
//! BKL本体でGS化しても、この器の構造（`[T; MAX_CPUS]` を [`cpu_id`] で引く）は
//! そのままである。GS化で変わるのは [`cpu_id`] がGS（またはAPIC ID）読みになる点
//! だけで、[`PerCpu::this_cpu`] は依然として配列を索引する。得られるのは
//! [`cpu_id`] の高速化であって、データ自体がGS相対オフセットへ移るわけではない。
//! したがってfalse sharing（[`MAX_CPUS`] の注意）はGS化しても残り、アクセスは
//! 2段（`cpu_id()` → 索引）のままである。BKLではカーネル内へ同時に入れるのは
//! 1コアだけで、per-CPUデータの同時アクセスは限られるため、これで十分である。
//!
//! データ自体をGS相対オフセットへ置く「集約ブロック形式」（コアごとに1つの
//! per-CPUブロックをGSベースへ置き、`gs:[offset]` で直に読む）にするなら、
//! [`PerCpu`] から集約ブロックへの移行が別途必要になる（false sharingの解消も
//! そこで行う）。これはフル細粒度SMP（`vision.md`）へ進むときに検討する。

/// サポートするCPU数の上限。
///
/// シングルコア前提（ADR-0002）なので現状は `1`。BKL本体でAP起こしを実装する
/// 際に、実際のコア数の上限へ引き上げる。
///
/// # `MAX_CPUS > 1` にするときの注意
///
/// per-CPUデータを `[T; MAX_CPUS]` で持つと、`MAX_CPUS > 1` では隣接要素が同一
/// キャッシュラインに載りうる。[`crate::critical`] の入れ子深さのようなホットな
/// カウンタでは、これがfalse sharingとして実測できる差になる。BKLでは競合が
/// 限られ性能は当面の目標でないので現在の素朴な配列で問題ないが、`MAX_CPUS > 1`
/// にする際は、各要素をキャッシュライン境界へアラインするか、データ自体を
/// コアごとの別領域へ置く集約ブロック形式（モジュールドキュメントのGS化の節を
/// 参照）へ移す必要がある。単に [`cpu_id`] をGS読みへ差し替えるだけでは、
/// 配列索引が残るためfalse sharingは解消しないことに注意する。
pub const MAX_CPUS: usize = 1;

/// 現在実行中のCPUの番号（`0..MAX_CPUS`）を返す。
///
/// # 現状は常に `0`
///
/// シングルコア前提（ADR-0002）のため、当面は無条件に `0` を返す。BKL本体で
/// APIC ID / GSベースから実際の番号を読む形へ差し替える。
///
/// # `0` を返すことに依存したコードを書かないこと
///
/// 「どうせ `0` だから」という理由で境界チェックを省いたり、配列の先頭要素を
/// 直接触ったりしてはならない。そうしたコードは `MAX_CPUS > 1` にした瞬間に
/// 静かに壊れる。per-CPUデータへは必ず [`PerCpu::this_cpu`] 経由でアクセスし、
/// 索引はこの関数の戻り値を使う。
#[inline]
pub fn cpu_id() -> usize {
    0
}

/// CPUごとに 1 つずつ値を持つ器。
///
/// 実データは `[T; MAX_CPUS]` で保持し、[`this_cpu`][Self::this_cpu] が
/// [`cpu_id`] で現在のCPUの要素を引く。`AtomicUsize` のような内部可変な `T` を
/// 入れれば、`&T` 経由でそのまま更新できる（[`crate::critical`] の入れ子深さが
/// この形になる）。
///
/// `T: Sync` なら `PerCpu<T>` も自動で `Sync` になる（`[T; N]` の `Sync` を
/// そのまま継ぐ）ので、`static` として置ける。
pub struct PerCpu<T> {
    slots: [T; MAX_CPUS],
}

impl<T> PerCpu<T> {
    /// 各CPUの初期値を与えて器を作る。
    ///
    /// `const fn` なので `static` の初期化子として使える。
    pub const fn new(slots: [T; MAX_CPUS]) -> Self {
        Self { slots }
    }

    /// 現在のCPU（[`cpu_id`]）に対応する要素への参照を返す。
    ///
    /// 索引は必ず [`cpu_id`] 経由で、`0` 決め打ちにしない（[`cpu_id`] の注意を
    /// 参照）。BKL本体でGS化しても索引する構造自体は変わらず、[`cpu_id`] の
    /// 実装だけがGS（またはAPIC ID）読みへ差し替わる（モジュールドキュメントの
    /// GS化の節を参照）。
    #[inline]
    pub fn this_cpu(&self) -> &T {
        &self.slots[cpu_id()]
    }
}
