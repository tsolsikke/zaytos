//! CR3 の読み取り・切り替え（M2-d, d-2）。
//!
//! CR3 の書き換えは実行中のコードから
//! 見えるメモリ写像そのものを変える操作であり、意図的にホスト
//! `cargo test` の対象にしていない。

/// 現在の CR3 の値を読む。
///
/// アドレス部分（bit 12〜51）に加え、PCID 関連ビットや PWT/PCD
/// （PCID 無効時）もそのまま含めて返す。呼び出し側が必要な部分だけ
/// マスクして使うこと。
pub fn read_cr3() -> u64 {
    let value: u64;
    // SAFETY: `mov reg, cr3` は読み取り専用でメモリ・スタックに副作用が
    // ない。ただし CR3 の値そのものは実行環境（ページテーブル）に
    // 依存するため、意図的に `options` は指定していない（保守的に扱う）。
    unsafe {
        core::arch::asm!("mov {}, cr3", out(reg) value);
    }
    value
}

/// CR3 を `pml4_phys` に切り替える。
///
/// `pml4_phys` は 4KiB アラインされた新しい PML4 の物理アドレスであること
/// （呼び出し側が検証済みであること）。この関数自身は下位ビット（PWT/PCD
/// を含む）をマスクしない。呼び出し側が「アドレス部分のみ、フラグ
/// ビットは 0」の値を渡すこと。
///
/// # Safety
/// 呼び出し時点で `pml4_phys` が指す新しいページテーブル一式が、現在
/// 実行中のコード・現在のスタック・`pml4_phys` 自身が指すフレームを
/// 含め、恒等マッピング（仮想アドレス = 物理アドレス）により引き続き
/// アクセス可能であることが、呼び出し側（`main.rs` の d-1 必須領域
/// 検証）で確認済みであること。この前提が崩れていると、この命令の
/// 実行中またはその直後の命令フェッチ・スタックアクセスで
/// トリプルフォルトする。
///
/// `options` は意図的に何も指定していない。CR3 の書き換えはメモリの
/// 見え方（今後のロード/ストアがどの物理アドレスを指すか）そのものを
/// 変えるため、`nomem`（「メモリに触れない」という宣言）を付けるのは
/// 誤りであり、コンパイラによる命令の並べ替え・最適化を許してはならない。
pub unsafe fn switch_to(pml4_phys: u64) {
    // SAFETY: 呼び出し元契約を参照。
    unsafe {
        core::arch::asm!("mov cr3, {}", in(reg) pml4_phys);
    }
}
