//! システムコールの頼みの形（番号と 6 つの引数）。**CPU によらない**——x86_64 も aarch64 も、番号を 1 つのレジスタで、
//! 引数を 6 つまでのレジスタで渡す（`man 2 syscall` の表。`manpages-dev` 6.7。2026-09-30）。**どのレジスタから読むかは
//! CPU によって違う**ので、読む関数と書き戻す関数は [`super::x86_64`] にある（`ADR-0071` の決定 1 の 2 で、
//! `abi/linux/x86_64` の `registers` から分けた。2026-09-30）。

/// システムコールの番号と 6 つの引数（入口の文脈から読んだもの）。
pub struct SyscallRequest {
    pub number: u64,
    pub args: [u64; 6],
}
