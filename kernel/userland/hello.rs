//! `hello`: 埋め込み ELF から Ring 3 で走る最初のユーザープログラム（S9-b-1）。
//!
//! # crate ではない
//!
//! このファイルは cargo のパッケージに属さない。`kernel/build.rs` が `rustc` を
//! 1 回呼んで単独でリンクし、できた ELF を kernel が `include_bytes!` で抱える。
//! cargo を入れ子にしないのは、`--full` が kernel を feature 構成ごとに何十回も
//! 建てるためである（詳細は `build.rs`）。
//!
//! **`cargo fmt` と `clippy` はこのファイルを見ない。** crate に属さないためで
//! ある。対象へ入れるのは、ユーザープログラムが 3 本を超えるとき、または 1 本が
//! 100 行を超えるときとする。
//!
//! # 何をするか
//!
//! `write(1, "...", n)` を `int 0x80` で 1 回発行し、`exit(0)` で終わる（S9-b-3-1）。
//!
//! **出口が `ud2` から `exit` へ変わった。** S9-b-1 の時点ではプロセスの実体が
//! 無く、終了させる先が無かったので、S8 が作った畳みの機構（`FOLDABLE_VECTORS` に
//! ベクタ 6 が在る）へ `ud2` で乗っていた。**いまは終了する先がある。**
//!
//! **`exit` の直後に `ud2` を残してある。** `exit` がカーネルへ戻らないはずの
//! 呼び出しなので、**戻ってきた場合の行き先を用意していないとゼロ埋めを実行する**
//! （下の `.org` の注記と同じ理由）。受け皿がここに在ることで、
//! 「`exit` が効かなかった」が確定的な #UD として現れる。

#![no_std]
#![no_main]

core::arch::global_asm!(
    // **entry の手前に詰め物を置く。**
    //
    // 詰め物が無いと、`_start` が最初の `PT_LOAD` の先頭と同じアドレスになる。
    // すると「entry ではなくセグメントの先頭へ飛ぶ」破壊が破壊にならない。
    //
    // **像を破壊のために歪めているのではなく、より一般的な形にしている。**
    // 実際の ELF は `.text` の前に別の節が来るので、entry とセグメントの先頭は
    // 一致しないほうが普通である。極小のプログラムだけが一致する。
    //
    // 中身は `ud2` で埋める。ここへ飛んだ場合は先頭で #UD になり、
    // 正しい entry から走ったときの畳み位置（`int 0x80` の後）と RIP で区別できる。
    ".section .text.prepad,\"ax\"",
    ".rept 8",
    "  ud2",
    ".endr",

    ".section .text._start,\"ax\"",
    ".globl _start",
    "_start:",
    // write(fd=1, buf=MESSAGE, len)。番号と引数の並びは Linux x86-64（ADR-0020）。
    "  mov rax, 1",
    "  mov rdi, 1",
    "  lea rsi, [rip + MESSAGE]",
    "  mov rdx, {message_len}",
    "  int 0x80",
    // プロセスの終了。**ここから戻らない。**
    //
    // **位置を固定する。** カーネルは終了が効かなかったときの畳み位置を
    // `entry + 0x30` として主張する。命令の長さはアセンブラの選択（`mov eax,1` か
    // `mov rax,1` か）で変わるので、`.org` で揃えておく。**ずれたら判定行が
    // 落ちるので、食い違いは静かに残らない。**
    // **詰め物は 0x90（nop）で埋める。** 既定の詰め物はゼロで、ゼロは
    // `add [rax], al` として実行される。実測でそうなった——`int 0x80` の後、
    // ゼロを実行し続けて `[rax]`（rax は write の戻り値 18）を触り、
    // `ud2` へ届く前に #PF で畳まれた。**詰め物は実行される。**
    ".org 0x20, 0x90",
    "  mov rax, 60",
    "  xor edi, edi",
    "  int 0x80",
    // **`exit` が戻ってきたときの受け皿。** 戻らない呼び出しの直後を空けておくと、
    // 詰め物（nop）を走り抜けて次に置かれたものを実行する。**破壊が成功した後の
    // 行き先を、破壊と一緒に用意する。**
    ".org 0x30, 0x90",
    "  ud2",

    ".section .rodata",
    "MESSAGE:",
    "  .ascii \"hello from ring 3\\n\"",
    message_len = const 18,
);

#[panic_handler]
fn panic(_info: &core::panic::PanicInfo) -> ! {
    // 到達しない。no_std のバイナリに必須なので置くだけである。
    loop {}
}
