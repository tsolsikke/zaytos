//! `fault-test`: Ring 3 で違反を起こして畳まれるユーザープログラム（S9-b-3-2a）。
//!
//! # crate ではない
//!
//! `hello.rs` と同じで、cargo のパッケージに属さない。`kernel/build.rs` が
//! `rustc` を 1 回呼んで単独でリンクし、できた ELF を kernel が `include_bytes!`
//! で抱える。**`cargo fmt` と `clippy` はこのファイルを見ない。**
//!
//! # 何をするか
//!
//! **自分の `.text` へ 1 バイト書く。** ローダーは `PT_LOAD` の `W` を落として
//! 張るので（S9-a の `writable` 引数）、Ring 3 からの書きは #PF になる。
//! `exit` は呼ばない。**このプロセスは畳みで終わる。**
//!
//! # なぜ #PF を選ぶか
//!
//! **`ud2` は `hello` が既に通った道である**（S9-b-1）。#PF なら、S8 が畳む
//! 4 ベクタのうち最も情報の多い署名を通せる——**エラーコードが「不在」と
//! 「権限違反」を区別し**（S7 の到達条件 3 の観測と同じ区別）、CR2 が
//! 触った番地そのものを持つ。カーネル側はベクタ・フォルト RIP・CR2・
//! エラーコードの 4 つを既知の値と突き合わせられる。
//!
//! **実行してはいけないページへ飛ぶ形は採らない。** それは `EFER.NXE` の
//! 有効化を要求し、`W^X` の `X` の側の解禁条件（実行してはいけないページを
//! 張る必要が生じたとき）を発火させる。**発火させると、既存エントリの読み戻し
//! 検証、direct map とユーザースタックの NX 化まで芋づるで付いてくる。
//! それは独立の段の仕事である。**
//!
//! # この像は `hello` ほど直接には見られていない
//!
//! `verify_embedded_user_elf` が見ているのは `hello` の像だけで、詰め物が生きて
//! いること（entry が `PT_LOAD` の先頭と一致しないこと）を**原因の側で**確かめて
//! いる。**こちらは同じことを結果の側でしか見ていない**——詰め物が落ちれば
//! entry が `0x400000` になり、フォルト RIP が `entry + 0x20` の主張と食い違う。
//!
//! **二重には見ない**（既に捕まる形があるなら足さない）。**ただし、捕まる理由が
//! 違うことは書いておく。** 結果の側で見ているので、**詰め物以外の理由で RIP が
//! ずれても同じ判定行が落ちる。** 判定行はそれに合わせて「畳んだ位置が予期と違う」
//! までしか言わない。**原因を名指ししない**のは、名指しできる根拠がここに無いためである。
//!
//! # 書けてしまったときの行き先
//!
//! `W` が落ちていなければ書きは成功し、実行は次へ進む。**そのときの行き先を
//! 用意してある**（`.org 0x30` の `ud2`）。ベクタが 14 ではなく 6 になり、
//! カーネル側の判定行が食い違いとして止める。**破壊が成功した後の行き先を、
//! 破壊と一緒に用意する。**

#![no_std]
#![no_main]

core::arch::global_asm!(
    // **entry の手前に詰め物を置く**（`hello.rs` と同じ理由）。entry と最初の
    // `PT_LOAD` の先頭を一致させない。中身は `ud2` で、ここへ飛べば先頭で #UD に
    // なるので、正しい entry から走った場合と RIP で区別できる。
    ".section .text.prepad,\"ax\"",
    ".rept 8",
    "  ud2",
    ".endr",

    ".section .text._start,\"ax\"",
    ".globl _start",
    "_start:",
    // 書き込む先は自分の `.text` の先頭。**リンク先（`userland/user.ld` の
    // `0x400000`）と対になっている。** カーネルは CR2 がこの値であることを
    // 主張するので、食い違えば判定行が落ちる。
    "  mov rax, {text_base}",
    // **フォルトする命令の位置を固定する。** カーネルはフォルト RIP が
    // `entry + 0x20` であることを主張する。命令長はアセンブラの選択で変わるので
    // `.org` で揃える。**詰め物は 0x90（nop）で埋める**（ゼロは
    // `add [rax], al` として実行される。`hello.rs` の注記と同じ）。
    ".org 0x20, 0x90",
    "  mov byte ptr [rax], 0",
    // 書けてしまったときの受け皿。
    ".org 0x30, 0x90",
    "  ud2",

    text_base = const 0x0040_0000u64,
);

#[panic_handler]
fn panic(_info: &core::panic::PanicInfo) -> ! {
    // 到達しない。no_std のバイナリに必須なので置くだけである。
    loop {}
}
