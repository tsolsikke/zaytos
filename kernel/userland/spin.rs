//! `spin`: システムコールを出さずに回り続けるプログラム（S12 前の手当て、C）。
//!
//! # crate ではない
//!
//! `hello.rs` と同じで、`kernel/build.rs` が `rustc` を 1 回呼んで単独で
//! リンクする。**`cargo fmt` と `clippy` はこのファイルを見ない。**
//!
//! # 何をするか
//!
//! **1 行出してから、無限に回る。それだけである。**
//!
//! **回る前に 1 行出すのは、実際に走り始めたことを見るためである。**
//! 出さないと、**「止められた」と「そもそも起きなかった」がログから区別できない。**
//!
//! # なぜこれが要るのか
//!
//! **中断（Ctrl+C）が止めたい相手そのものだからである。**
//!
//! `read` を出して待っている子なら、前景を通してバイトが届くので、
//! **ユーザー側で 0x03 を見て自分で終わることもできる。**
//! **システムコールを出さない子には、その道が無い**——
//! **デコードの経路（`crate::input::read_bytes`）自体が動かない。**
//!
//! **したがって、カーネルが外から止められることを主張するには、
//! この形の子が要る。** 既存の 6 本はどれも短く終わるので、
//! **止める対象として使えない。**
//!
//! # 終わらない
//!
//! **`exit` を持たない。** 止められなければ永久に回る。
//! **`--shell-test` はこれを Ctrl+C で止め、プロンプトが戻ることを見る。**
//! **止まらなければ、あちらは待ち時間の上限で落ちる。**

#![no_std]
#![no_main]

core::arch::global_asm!(
    // `hello` と同じ詰め物。entry とセグメント先頭を一致させない。
    ".section .text.prepad,\"ax\"",
    ".rept 8",
    "  ud2",
    ".endr",

    ".section .text._start,\"ax\"",
    ".globl _start",
    "_start:",
    // write(fd=1, buf=MESSAGE, len)。走り始めたことの証拠を 1 行出す。
    "  mov rax, 1",
    "  mov rdi, 1",
    "  lea rsi, [rip + MESSAGE]",
    "  mov rdx, {message_len}",
    "  int 0x80",
    // **ここから先はシステムコールを出さない。**
    //
    // **`hlt` にしない。** Ring 3 の `hlt` は特権命令で #GP になり、
    // **畳みの経路で止まってしまう**——それでは「止まらない子」にならない。
    // **`pause` を挟むのは TCG に優しくするためで、意味は無限ループである。**
    "2:",
    "  pause",
    "  jmp 2b",

    ".section .rodata",
    "MESSAGE:",
    "  .ascii \"spin: running\\n\"",
    message_len = const 14,
);

#[panic_handler]
fn panic(_info: &core::panic::PanicInfo) -> ! {
    // 到達しない。no_std のバイナリに必須なので置くだけである。
    loop {}
}
