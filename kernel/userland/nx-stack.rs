//! `nx-stack`: Ring 3 で、実行できないページへ跳んで終了させられるユーザープログラム（2026-10-03）。
//!
//! # crate ではない
//!
//! `fault-test.rs` と同じで、cargo のパッケージに属さない。`kernel/build.rs` が `rustc` を 1 回呼んで単独で
//! リンクし、できた ELF を kernel が `include_bytes!` で抱える。**`cargo fmt` と `clippy` はこのファイルを見ない。**
//!
//! # 何をするか
//!
//! **自分のスタックのページの先頭へ `ud2` を書き、そこへ跳ぶ。**スタックは、書けて実行しないページである。**** ローダーは、実行しない権限のページに実行禁止の印を付けて写すので、Ring 3 が
//! そこから命令を取り出そうとした時点で #PF になる。`exit` は呼ばない。**このプロセスは、例外による終了処理で終わる。**
//!
//! カーネルの側は、ベクタ（14）・止まった番地・CR2・誤りコード（存在・ユーザー・命令の取り出し＝0x15）を、
//! 決まった値と突き合わせる（`kernel/src/main.rs` の `USER_PROGRAMS`）。**止まった番地と CR2 は、跳んだ先の番地で
//! ある**——命令の取り出しの違反は、取り出そうとした番地で起きる。
//!
//! # 起動ログの「スタックの使用量」が 100% と出る
//!
//! 受け皿を、スタックのページの先頭（いちばん下）に書くので、使用量を下から数える行（`user-stack:`）は、
//! 4096 のうち 4096 を使ったと出る。判定には使っていない行である。
//!
//! # 実行できてしまったときの行き先
//!
//! **跳んだ先には `ud2` を置いてある。** 実行禁止が効いていなければ、そこで #UD になり、ベクタが 14 ではなく 6 に
//! なる。カーネルの側の判定行が、食い違いとして止める。**破壊が成功した後の行き先を、破壊と一緒に用意する。**

#![no_std]
#![no_main]

core::arch::global_asm!(
    // **entry の手前に詰め物を置く**（`hello.rs` と同じ理由）。entry と最初の `PT_LOAD` の先頭を一致させない。
    ".section .text.prepad,\"ax\"",
    ".rept 8",
    "  ud2",
    ".endr",

    ".section .text._start,\"ax\"",
    ".globl _start",
    "_start:",
    // 跳ぶ先は、スタックのページの先頭。**ローダーが置くスタックの番地（`kernel/src/userland.rs` の
    // `USER_PROGRAM_STACK_TOP` から 1 ページ下）と対になっている。** 引数は上端の側に積まれるので、先頭は空いている。
    "  mov rax, {stack_page}",
    // 実行できてしまったときの受け皿を、跳ぶ先に書く（スタックは書ける）。
    "  mov word ptr [rax], 0x0b0f",
    "  jmp rax",

    stack_page = const 0x007f_f000u64,
);

#[panic_handler]
fn panic(_info: &core::panic::PanicInfo) -> ! {
    // 到達しない。no_std のバイナリに必須なので置くだけである。
    loop {}
}
